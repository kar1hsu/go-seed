CREATE TABLE IF NOT EXISTS roles (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 code VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 name VARCHAR(64) NOT NULL,
 description VARCHAR(255) NOT NULL DEFAULT '',
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 built_in BOOLEAN NOT NULL DEFAULT FALSE,
 created_at DATETIME(6) NOT NULL,
 updated_at DATETIME(6) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS permissions (
 code VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
 name VARCHAR(64) NOT NULL,
 group_name VARCHAR(64) NOT NULL,
 kind VARCHAR(16) NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS admin_roles (
 admin_id BIGINT UNSIGNED NOT NULL,
 role_id BIGINT UNSIGNED NOT NULL,
 PRIMARY KEY (admin_id,role_id),
 CONSTRAINT fk_ar_admin FOREIGN KEY (admin_id) REFERENCES administrators(id) ON DELETE CASCADE,
 CONSTRAINT fk_ar_role FOREIGN KEY (role_id) REFERENCES roles(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS role_permissions (
 role_id BIGINT UNSIGNED NOT NULL,
 permission_code VARCHAR(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 PRIMARY KEY (role_id,permission_code),
 CONSTRAINT fk_rp_role FOREIGN KEY (role_id) REFERENCES roles(id) ON DELETE CASCADE,
 CONSTRAINT fk_rp_permission FOREIGN KEY (permission_code) REFERENCES permissions(code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS policy_states (
 id INT NOT NULL PRIMARY KEY,
 version BIGINT UNSIGNED NOT NULL,
 bootstrapped BOOLEAN NOT NULL DEFAULT FALSE
) ENGINE=InnoDB;
